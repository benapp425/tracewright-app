"""Example design: a USB-C powered ATtiny85 board with a Qwiic I2C port.

It is the toolkit's self-test fixture and a worked example of generating a schematic with tw.sch:

  schematic(hw_dir)   the hierarchical schematic (root + Power + MCU sheets)
  outline_op()        the board outline op (50 x 35 mm, 2 mm corners)
  placement()         where every footprint goes, and why

Parts are from JLC stock (queried 2026-09-26). ATTINY85-20SU is the 208-mil SOIC-8 (5.3 mm body):
it takes Package_SO:SOIC-8_5.3x5.3mm_P1.27mm, not the 3.9 mm SOIC-8 -- the distributor's package
field is what showed it.
"""
from tw.sch import Design, Part, stock


