WIDE = ADV["M"]
_MARK = re.compile(r"([~^_])\{([^{}]*)\}")


def _glyphs(line):
    """The drawn characters of a line with their scale: KiCad's markup ~{overbar}, ^{superscript}, _{subscript}."""
    out, last = [], 0
    for m in _MARK.finditer(line):
        out += [(c, 1.0) for c in line[last:m.start()]]
        out += [(c, 1.0 if m.group(1) == "~" else 0.8) for c in m.group(2)]
        last = m.end()
    return out + [(c, 1.0) for c in line[last:]]


def width(text, size=SIZE, pen=None):
    """The width of the text's box as KiCad sizes it, in mm (the widest line of a multi-line text)."""
    best = 0.0
    for line in str(text).split("\n"):
        best = max(best, sum(ADV.get(c, WIDE) * k for c, k in _glyphs(line)))
    if best == 0:
        return 0.0
    return best * size / SIZE + (PEN * size / SIZE if pen is None else pen)


def ink(text, size=SIZE):
    """(start, end) of the strokes along the line, in mm from a left-justified text's anchor (widest line)."""
    lo, hi = None, 0.0
    for line in str(text).split("\n"):
        g = _glyphs(line)
        while g and g[-1][0] == " ":
            g.pop()
        lead = 0.0
        while g and g[0][0] == " ":
            lead += ADV[" "] * g[0][1]
            g.pop(0)
        if not g:
            continue
        a = lead + INK_L.get(g[0][0], INK_L["M"]) * g[0][1]
        z = lead + sum(ADV.get(c, WIDE) * k for c, k in g[:-1]) + INK_R.get(g[-1][0], INK_R["M"]) * g[-1][1]
        lo = a if lo is None else min(lo, a)
        hi = max(hi, z)
    if lo is None:
        return (0.0, 0.0)
    return (lo * size / SIZE, hi * size / SIZE)


def ink_width(text, size=SIZE):
    a, z = ink(text, size)
    return z - a
